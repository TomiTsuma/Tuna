#!/usr/bin/env python3
"""Generates the sources of a tracing pass-through nvcuda.dll.

Every export of the real driver DLL becomes a two-instruction x86-64 thunk:
count the call, then jump to the real function. cuGetProcAddress(_v2) and
cuGetExportTable are wrapped in C (trace.c) so that pointers handed out by the
driver are swapped for our thunks and hidden-table requests are logged.

Usage: gen_trace.py REAL_NVCUDA_DLL OUT_DIR
Writes OUT_DIR/thunks.S, OUT_DIR/exports.def and OUT_DIR/names.inc.
"""

import struct
import sys
from pathlib import Path

# Exported by trace.c instead of a plain thunk.
WRAPPED = {"cuGetProcAddress", "cuGetProcAddress_v2", "cuGetExportTable"}


def pe_exports(path):
    """Names in a PE file's export directory (no third-party parser needed)."""
    data = Path(path).read_bytes()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if data[pe:pe + 4] != b"PE\0\0":
        raise SystemExit(f"{path}: not a PE file")
    sections_count = struct.unpack_from("<H", data, pe + 6)[0]
    optional_size = struct.unpack_from("<H", data, pe + 20)[0]
    optional = pe + 24
    if struct.unpack_from("<H", data, optional)[0] != 0x20B:
        raise SystemExit(f"{path}: not a 64-bit PE")
    export_rva = struct.unpack_from("<I", data, optional + 112)[0]

    sections = []
    for i in range(sections_count):
        s = optional + optional_size + 40 * i
        vsize, va, raw_size, raw_ptr = struct.unpack_from("<IIII", data, s + 8)
        sections.append((va, max(vsize, raw_size), raw_ptr))

    def offset(rva):
        for va, size, raw in sections:
            if va <= rva < va + size:
                return rva - va + raw
        raise SystemExit(f"RVA {rva:#x} outside every section")

    d = offset(export_rva)
    names_count, = struct.unpack_from("<I", data, d + 24)
    names_rva, = struct.unpack_from("<I", data, d + 32)
    names = []
    for i in range(names_count):
        name_rva = struct.unpack_from("<I", data, offset(names_rva) + 4 * i)[0]
        start = offset(name_rva)
        names.append(data[start:data.index(b"\0", start)].decode())
    return sorted(names)


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    names = pe_exports(sys.argv[1])
    out = Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)

    asm = ["# Generated by gen_trace.py. Do not edit.", ".text"]
    for i, name in enumerate(names):
        asm += [f".globl tuna_thunk_{name}", f"tuna_thunk_{name}:",
                f"    lock incq tuna_counts+{8 * i}(%rip)",
                f"    jmp *tuna_real+{8 * i}(%rip)"]
    asm += [".section .rdata", ".globl tuna_thunks", ".p2align 3", "tuna_thunks:"]
    asm += [f"    .quad tuna_thunk_{name}" for name in names]
    (out / "thunks.S").write_text("\n".join(asm) + "\n")

    exports = ["LIBRARY nvcuda", "EXPORTS"]
    for name in names:
        exports.append(f"    {name}={'tuna_' + name if name in WRAPPED else 'tuna_thunk_' + name}")
    (out / "exports.def").write_text("\n".join(exports) + "\n")

    (out / "names.inc").write_text(
        "/* Generated by gen_trace.py. */\n"
        f"#define TUNA_EXPORT_COUNT {len(names)}\n"
        "static const char* const tuna_names[TUNA_EXPORT_COUNT] = {\n"
        + "".join(f'    "{name}",\n' for name in names) + "};\n")
    print(f"{len(names)} exports")


if __name__ == "__main__":
    main()
